#!/usr/bin/env python3
"""Summarise the Yosys statistics in results/synthesis/ into results/synthesis/SUMMARY.md.
Every number is parsed from the *_stat.txt and *.log files written by scripts/run_synthesis.sh; none is typed in."""
import re
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "results" / "synthesis"


def parse(path):
    """-> {module: {cell_type: count}} from a Yosys `stat` report (design-hierarchy section keyed '(total)')."""
    mods, cur, in_hier = {}, None, False
    for line in path.read_text().splitlines():
        m = re.match(r"=== (.+) ===", line)
        if m:
            cur = m.group(1); in_hier = cur == "design hierarchy"
            cur = "(total)" if in_hier else re.sub(r"^\$paramod\$[0-9a-f]+\\|^\$paramod\\", "", cur)
            mods[cur] = {}
            continue
        m = re.match(r"\s+(\d+)\s+(\S+)\s*$", line)
        if m and cur is not None:
            mods[cur][m.group(2)] = int(m.group(1))
        m = re.match(r"\s+(\d+) cells\s*$", line)
        if m and cur is not None:
            mods[cur]["cells"] = int(m.group(1))
    return mods


def ffs(c):
    return sum(v for k, v in c.items() if "DFF" in k)


def top(mods):
    return mods.get("(total)") or mods["cache_controller"]


gf, ge, ie = parse(OUT / "generic_flat_stat.txt"), None, parse(OUT / "ice40_stat.txt")
ih = parse(OUT / "ice40_hier_stat.txt")
g, i = top(gf), top(ie)
lines = ["# Synthesis summary (generated by scripts/synth_summary.py)", "",
         "Source: Yosys statistics in this directory. Software synthesis estimates only: no place-and-route, no timing analysis, "
         "no FPGA hardware. The iCE40 flow is a representative resource model, not a selected target device.", "",
         "## Generic (technology-independent) flow, flattened", "",
         "Memories are not inferred as RAM here; Yosys expands them into flip-flops and multiplexers, so this is what the design "
         "costs without block RAM.", "",
         f"| Cells | Flip-flops | Combinational cells |", "|---|---|---|",
         f"| {g['cells']} | {ffs(g)} | {g['cells'] - ffs(g) - g.get('$scopeinfo', 0)} |", "",
         "Cell types: " + ", ".join(f"{k} {v}" for k, v in sorted(g.items()) if k.startswith("$_")), "",
         "## iCE40 flow, flattened (RAM inferred)", "",
         "| Total cells | LUT4 | Flip-flops | Carry | Block RAM (SB_RAM40_4K) |", "|---|---|---|---|---|",
         f"| {i['cells']} | {i.get('SB_LUT4', 0)} | {ffs(i)} | {i.get('SB_CARRY', 0)} | {i.get('SB_RAM40_4K', 0)} |", "",
         "## Per module (iCE40, hierarchy kept; numbers are larger than the flat design because cross-module optimisation is disabled)", "",
         "| Module | Cells | LUT4 | Flip-flops | Block RAM |", "|---|---|---|---|---|"]
for name, c in ih.items():
    if name == "(total)" or "cells" not in c:
        continue
    lines.append(f"| {name} | {c['cells']} | {c.get('SB_LUT4', 0)} | {ffs(c)} | {c.get('SB_RAM40_4K', 0)} |")
t = ih.get("(total)")
if t:
    lines.append(f"| **hierarchy total** | {t['cells']} | {t.get('SB_LUT4', 0)} | {ffs(t)} | {t.get('SB_RAM40_4K', 0)} |")
lines += ["", "## Memory structures", ""]
d = next((c for n, c in ih.items() if n.endswith("cache_data_ram")), {})
tg = next((c for n, c in ih.items() if n.endswith("cache_tag_ram")), {})
lines += [f"- Data array: {d.get('SB_RAM40_4K', 0)} block RAMs (one per byte lane, 16 lanes x 64 lines x 8 bit).",
          f"- Tag array: {tg.get('SB_RAM40_4K', 0)} block RAM(s) (64 lines x 22 bit).",
          "- Valid bits: flip-flops (64), not RAM, because they must all clear on reset.", "",
          "## Warnings in the Yosys logs", ""]
warn = {}
for log in sorted(OUT.glob("*.log")):
    for line in log.read_text(errors="replace").splitlines():
        if re.search(r"warning", line, re.I) and "network is combinational" not in line:
            key = re.sub(r"/[^ ]*abc9_map\.v", "abc9_map.v", line.strip())
            warn[key] = warn.get(key, 0) + 1
lines += [f"- {n}x {w}" for w, n in warn.items()] or ["- none"]
lines += ["", "The `bit` lexer warning (if listed) comes from Yosys's own `abc9_map.v` helper, not from this project's RTL.", ""]
(OUT / "SUMMARY.md").write_text("\n".join(lines))
print((OUT / "SUMMARY.md").read_text())
